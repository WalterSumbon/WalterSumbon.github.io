export function weaponStats(index, peak) {
  const w = { ...WEAPONS[index] };
  for (const [at, i, key, mul] of UPGRADES)
    if (i === index && peak >= at)
      w[key] = key === "cluster" ? mul : (w[key] || 0) * mul;
  return w;
}
